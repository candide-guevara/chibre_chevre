import 'dart:ui';

import 'package:chibre_core/chibre_core.dart';

import 'geometry.dart';

/// A suit symbol [size] tall, centred on [center].
Path suitShape(Suit suit, Offset center, double size) {
  final s = size / 2;
  Offset p(double x, double y) => center + Offset(x * s, y * s);
  switch (suit) {
    case Suit.hearts:
      return bezier(p(0, 0.92), [
        (p(-0.28, 0.62), p(-1.0, 0.22), p(-1.0, -0.32)),
        (p(-1.0, -0.74), p(-0.7, -0.96), p(-0.46, -0.96)),
        (p(-0.2, -0.96), p(-0.04, -0.8), p(0, -0.6)),
        (p(0.04, -0.8), p(0.2, -0.96), p(0.46, -0.96)),
        (p(0.7, -0.96), p(1.0, -0.74), p(1.0, -0.32)),
        (p(1.0, 0.22), p(0.28, 0.62), p(0, 0.92)),
      ]);
    case Suit.diamonds:
      return bezier(p(0, -1.0), [
        (p(0.22, -0.62), p(0.45, -0.32), p(0.74, 0)),
        (p(0.45, 0.32), p(0.22, 0.62), p(0, 1.0)),
        (p(-0.22, 0.62), p(-0.45, 0.32), p(-0.74, 0)),
        (p(-0.45, -0.32), p(-0.22, -0.62), p(0, -1.0)),
      ]);
    case Suit.spades:
      return bezier(p(0, -0.98), [
        (p(0.3, -0.62), p(1.0, -0.3), p(1.0, 0.16)),
        (p(1.0, 0.5), p(0.76, 0.68), p(0.52, 0.68)),
        (p(0.32, 0.68), p(0.16, 0.6), p(0.08, 0.46)),
        (p(0.1, 0.7), p(0.24, 0.88), p(0.44, 0.98)),
        (p(0.2, 0.98), p(-0.2, 0.98), p(-0.44, 0.98)),
        (p(-0.24, 0.88), p(-0.1, 0.7), p(-0.08, 0.46)),
        (p(-0.16, 0.6), p(-0.32, 0.68), p(-0.52, 0.68)),
        (p(-0.76, 0.68), p(-1.0, 0.5), p(-1.0, 0.16)),
        (p(-1.0, -0.3), p(-0.3, -0.62), p(0, -0.98)),
      ]);
    case Suit.clubs:
      final r = 0.4 * s;
      final stem = bezier(p(-0.08, 0.2), [
        (p(-0.1, 0.62), p(-0.24, 0.86), p(-0.46, 0.98)),
        (p(-0.2, 0.98), p(0.2, 0.98), p(0.46, 0.98)),
        (p(0.24, 0.86), p(0.1, 0.62), p(0.08, 0.2)),
      ]);
      return union([
        circle(p(0, -0.52), r),
        circle(p(-0.54, 0.12), r),
        circle(p(0.54, 0.12), r),
        circle(p(0, 0.06), r * 0.6),
        stem,
      ]);
  }
}
